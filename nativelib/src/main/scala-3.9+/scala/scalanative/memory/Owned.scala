package scala.scalanative.memory

import scala.scalanative.runtime.OwnedAllocator

import language.experimental.captureChecking
import language.experimental.separationChecking

/** Base trait for objects with Rust-like ownership semantics.
 *
 *  Instances of classes extending `Owned` are not allocated on the garbage
 *  collected heap. Instead, the `scalanative-ownership` compiler phase uses
 *  the information established by separation checking to free them
 *  deterministically, mirroring Rust's ownership model:
 *
 *    - Every owned value has exactly one owner: a local `val`/`var`, a
 *      `consume` parameter, the receiver of a `consume` method, or an owning
 *      field of another `Owned` object.
 *    - Ownership is moved by passing the value to a `consume` parameter,
 *      calling a `consume` method on it, returning it, assigning it to a
 *      field or `var`, or binding it to a `val` with an explicit type. The
 *      separation checker rejects any use of a value after it was moved.
 *    - Any other use is a borrow. A borrow may not outlive its owner.
 *    - When the owner goes out of scope (normally, through `return`, or with
 *      an exception) and the value was not moved, it is dropped: its
 *      [[drop]] hook runs, then its owning fields are dropped in declaration
 *      order, then its memory is freed.
 *
 *  Code that creates or owns `Owned` values has to be compiled with
 *  `import language.experimental.separationChecking`.
 *
 *  {{{
 *  import language.experimental.separationChecking
 *  import scala.scalanative.memory.Owned
 *
 *  class File(val fd: Int) extends Owned:
 *    override def drop(): Unit = close(fd)
 *
 *  def process(consume f: File): Unit = ... // dropped when process returns
 *
 *  def main(): Unit =
 *    val a = File(open("a.txt"))
 *    val b = File(open("b.txt"))
 *    process(a)      // `a` is moved; using it afterwards is a compile error
 *    println(b.fd)   // borrow
 *  // `b` is dropped here
 *  }}}
 */
trait Owned extends caps.Mutable {

  /** Destructor, the equivalent of Rust's `Drop::drop`.
   *
   *  Called exactly once, right before the owning fields of this object are
   *  dropped and its memory is freed. It must not be called explicitly, use
   *  [[Owned.drop]] to drop a value early.
   */
  update def drop(): Unit = ()

  /** Drop glue: drops the owning fields of this object. Implemented by the
   *  compiler for every class that has owning fields.
   */
  update def scalanative$dropOwnedFields(): Unit = ()
}

object Owned {

  /** Drops `value` now, the equivalent of Rust's `std::mem::drop`.
   *
   *  The value is moved into this method, which owns it and therefore drops
   *  it when it returns.
   */
  def drop(consume value: Owned^): Unit = ()

  /** Number of owned objects that are currently allocated. */
  def liveCount(): Long = OwnedAllocator.liveCount()

  /** Number of bytes used by owned objects that are currently allocated. */
  def liveBytes(): Long = OwnedAllocator.liveBytes()

  /** Number of owned objects freed so far. */
  def totalFreed(): Long = OwnedAllocator.totalFreed()

  /** Destroys an owned value: runs its destructor, drops its owning fields
   *  and frees its memory. Called by code generated by the compiler at the
   *  points where an owner goes out of scope.
   */
  def scalanative$destroy(value: Owned^): Unit =
    if (value != null) {
      value.drop()
      value.scalanative$dropOwnedFields()
      OwnedAllocator.free(value)
    }
}
